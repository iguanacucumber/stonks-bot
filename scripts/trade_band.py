"""Pre-registered trade-band sweep at IBKR with French tax.

See results/trade_band.md. Measures; does not change defaults.

Run: uv run python scripts/trade_band.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from bot import backtest, france, markets, strategy  # noqa: E402
from scripts.france import BASE  # noqa: E402

BANDS = (0.0, 0.025, 0.05, 0.10, 0.20)


def annual(eq: pd.Series, year: int) -> float:
    e = eq.loc[str(year)]
    return float(e.iloc[-1] / e.iloc[0] - 1.0) if len(e) > 2 else float("nan")


def main() -> None:
    panel, mem = markets.build("TECH")
    kw = dict(BASE)
    kw.update(france.kwargs("TECH", "Interactive Brokers", "cto", 10000, panel))
    rows = []
    for band in BANDS:
        cfg = strategy.Config(**{**kw, "trade_band": band})
        res = backtest.run(strategy.Market(panel, mem, cfg))
        f = france.after_tax(res, 10000, "TECH")
        rows.append(
            {
                "band": band,
                "after": f["after_tax_eur"] / 10000,
                "maxdd": f["maxdd"],
                "2018": annual(res.equity, 2018),
                "2022": annual(res.equity, 2022),
                "fees": f["fees_eur"],
                "tax": f["tax_paid_eur"],
                "exit": f["exit_tax_eur"],
                "trades": f["trades"],
            }
        )
        print(
            f"band {band:5.1%} after {rows[-1]['after']:6.2f}x  "
            f"maxDD {rows[-1]['maxdd']:6.1%}  2018 {rows[-1]['2018']:7.1%}  "
            f"2022 {rows[-1]['2022']:7.1%}  trades {rows[-1]['trades']}"
        )
    df = pd.DataFrame(rows)
    base = df[df.band == 0.0].iloc[0]
    lines = [
        "",
        "## Results",
        "",
        "| band | after tax | maxDD | 2018 | 2022 | fees | PFU paid | exit tax | trades |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r['band']:.1%} | **{r['after']:.2f}x** | {r['maxdd']:.1%} | "
            f"{r['2018']:.1%} | {r['2022']:.1%} | €{r['fees']:,.0f} | "
            f"€{r['tax']:,.0f} | €{r['exit']:,.0f} | {int(r['trades'])} |"
        )
    winners = df[
        (df.after > base.after)
        & (df.maxdd >= base.maxdd - 0.02)
        & (df["2018"] >= base["2018"])
        & (df["2022"] >= base["2022"])
        & (df.band > 0)
    ]
    verdict = (
        "**No band passes.** Keep 0; the monthly rebalance's tax/fee cost is "
        "smaller than the alpha lost by letting weights drift."
        if winners.empty
        else "**Initial pass:** "
        + ", ".join(f"{b:.1%}" for b in winners.band)
        + ". Check neighbors/all-year returns before adoption."
    )
    lines += ["", verdict, "", "Generated by `uv run python scripts/trade_band.py`."]
    with open(ROOT / "results" / "trade_band.md", "a") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"\n{verdict}")
    print("wrote results/trade_band.md")


if __name__ == "__main__":
    main()
