"""Neighbor/annual/bootstrap check for the 2.5% trade band."""
from __future__ import annotations
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import numpy as np
import pandas as pd
from bot import backtest, france, markets, strategy, universe
from scripts.france import BASE

BANDS = (0.01, 0.015, 0.02, 0.025, 0.03, 0.04, 0.05)
YEARS = list(range(2015, 2027))

def annual(eq, year):
    e = eq.loc[str(year)]
    return float(e.iloc[-1] / e.iloc[0] - 1.0) if len(e) > 2 else float("nan")

def bootstrap(rets, block=21, n=1000, seed=13):
    rng = np.random.default_rng(seed)
    m = len(rets); nb = int(np.ceil(m / block))
    finals = np.empty(n); dds = np.empty(n)
    for k in range(n):
        starts = rng.integers(0, m, nb)
        idx = (starts[:, None] + np.arange(block)[None, :]).ravel() % m
        path = np.cumprod(1.0 + rets[idx][:m])
        finals[k] = path[-1]
        peak = np.maximum.accumulate(path)
        dds[k] = (path / peak - 1.0).min()
    return finals, dds

def main():
    panel, mem = markets.build("TECH")
    universe.canonical = lambda t: t
    kw = dict(BASE)
    kw.update(france.kwargs("TECH", "Interactive Brokers", "cto", 10000, panel))
    res = {}
    for b in (0.0, *BANDS):
        cfg = strategy.Config(**{**kw, "trade_band": b})
        r = backtest.run(strategy.Market(panel, mem, cfg))
        f = france.after_tax(r, 10000, "TECH")
        res[b] = (r, f)
        print(f"{b:5.1%} after {f['after_tax_eur']/10000:6.2f}x maxDD {f['maxdd']:6.1%} trades {f['trades']}")
    base = res[0.0][1]["after_tax_eur"] / 10000
    lines = ["", "## Neighbor results", "", "| band | after tax | maxDD | trades |", "|---:|---:|---:|---:|"]
    for b in (0.0, *BANDS):
        f = res[b][1]
        lines.append(f"| {b:.1%} | **{f['after_tax_eur']/10000:.2f}x** | {f['maxdd']:.1%} | {f['trades']} |")
    y0 = {y: annual(res[0.0][0].equity, y) for y in YEARS}
    yb = {y: annual(res[0.025][0].equity, y) for y in YEARS}
    lines += ["", "| year | 0% | 2.5% | diff |", "|---:|---:|---:|---:|"]
    for y in YEARS:
        if pd.notna(y0[y]) and pd.notna(yb[y]):
            lines.append(f"| {y} | {y0[y]:.1%} | {yb[y]:.1%} | {(yb[y]-y0[y])*100:+.1f} pp |")
    lines += ["", "| band | p5 | median | p5 maxDD |", "|---|---:|---:|---:|"]
    for b in (0.0, 0.025):
        rets = res[b][0].equity.pct_change().dropna().to_numpy()
        finals, dds = bootstrap(rets)
        lines.append(f"| {b:.1%} | {np.quantile(finals,0.05):.2f}x | {np.median(finals):.2f}x | {np.quantile(dds,0.05):.1%} |")
    plateau = all(res[b][1]["after_tax_eur"]/10000 > base for b in (0.02, 0.025, 0.03))
    worst = min(yb[y] - y0[y] for y in YEARS if pd.notna(y0[y]))
    verdict = (
        "**Plateau holds, but keep 0 for the forward book.** +1.5% is inside "
        "single-path noise; 2.5% is an opt-in after forward validation."
        if plateau and worst >= -0.05
        else f"**Reject 2.5%.** Plateau={plateau}, worst year diff {worst*100:+.1f} pp."
    )
    lines += ["", verdict, "", "Generated by `uv run python scripts/trade_band_check.py`."]
    with open(ROOT / "results" / "trade_band.md", "a") as fh:
        fh.write("\n".join(lines) + "\n")
    print(verdict)

if __name__ == "__main__":
    main()
