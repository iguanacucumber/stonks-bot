"""Sleeve top_n sweep for the best French book at IBKR, after tax.

See results/topn_fr.md for the pre-registered rule.

Run: uv run python scripts/topn_fr.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from bot import backtest, france, markets, strategy, universe  # noqa: E402
from scripts.france import BASE  # noqa: E402

NS = (4, 5, 6, 7, 8, 10)


def bootstrap(rets: np.ndarray, block: int = 21, n: int = 1000, seed: int = 19):
    rng = np.random.default_rng(seed)
    m = len(rets)
    nb = int(np.ceil(m / block))
    finals = np.empty(n)
    dds = np.empty(n)
    for k in range(n):
        starts = rng.integers(0, m, nb)
        idx = (starts[:, None] + np.arange(block)[None, :]).ravel() % m
        path = np.cumprod(1.0 + rets[idx][:m])
        finals[k] = path[-1]
        peak = np.maximum.accumulate(path)
        dds[k] = (path / peak - 1.0).min()
    return finals, dds


def annual(eq: pd.Series, year: int) -> float:
    e = eq.loc[str(year)]
    return float(e.iloc[-1] / e.iloc[0] - 1.0) if len(e) > 2 else float("nan")


def main() -> None:
    panel, mem = markets.build("TECH")
    universe.canonical = lambda t: t
    kw = dict(BASE)
    kw.update(france.kwargs("TECH", "Interactive Brokers", "cto", 10000, panel))
    rows = []
    for n in NS:
        cfg = strategy.Config(**{**kw, "top_n": n})
        res = backtest.run(strategy.Market(panel, mem, cfg))
        f = france.after_tax(res, 10000, "TECH")
        finals, dds = bootstrap(res.equity.pct_change().dropna().to_numpy())
        rows.append(
            {
                "n": n,
                "after": f["after_tax_eur"] / 10000,
                "maxdd": f["maxdd"],
                "2018": annual(res.equity, 2018),
                "2022": annual(res.equity, 2022),
                "fees": f["fees_eur"],
                "tax": f["tax_paid_eur"],
                "trades": f["trades"],
                "p5": float(np.quantile(finals, 0.05)),
                "p5dd": float(np.quantile(dds, 0.05)),
            }
        )
        print(
            f"n={n:2d} after {rows[-1]['after']:6.2f}x maxDD {rows[-1]['maxdd']:6.1%} "
            f"2018 {rows[-1]['2018']:7.1%} 2022 {rows[-1]['2022']:7.1%} "
            f"p5 {rows[-1]['p5']:5.2f}x trades {rows[-1]['trades']}"
        )
    df = pd.DataFrame(rows)
    base = df[df.n == 6].iloc[0]
    lines = [
        "",
        "## Results",
        "",
        "| names | after tax | maxDD | 2018 | 2022 | fees | PFU paid | trades | boot p5 | p5 maxDD |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {int(r['n'])} | **{r['after']:.2f}x** | {r['maxdd']:.1%} | "
            f"{r['2018']:.1%} | {r['2022']:.1%} | €{r['fees']:,.0f} | "
            f"€{r['tax']:,.0f} | {int(r['trades'])} | {r['p5']:.2f}x | {r['p5dd']:.1%} |"
        )
    winners = df[
        (df.after > base.after)
        & (df.maxdd >= base.maxdd - 0.02)
        & (df["2018"] >= base["2018"])
        & (df["2022"] >= base["2022"])
        & (df.p5 >= base.p5)
        & (df.n != 6)
    ]
    verdict = (
        "**No breadth passes.** Keep 6; more names dilute the sleeve, fewer names "
        "add drawdown faster than after-tax return."
        if winners.empty
        else "**Passing breadth:** "
        + ", ".join(str(int(x)) for x in winners.n)
        + ". Check the neighbor cluster and start-date robustness before adoption."
    )
    lines += ["", verdict, "", "Generated by `uv run python scripts/topn_fr.py`."]
    with open(ROOT / "results" / "topn_fr.md", "a") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"\n{verdict}")
    print("wrote results/topn_fr.md")


if __name__ == "__main__":
    main()
