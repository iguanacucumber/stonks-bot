"""Year-by-year: does the shipped book beat each market's index consistently?

Shipped config (2.5x, daily 200-day cut, month-end, next open, 10 bps). For each
stock-level market, compare the bot's calendar-year return with its own index.

Run: uv run python scripts/yearly.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from bot import backtest, markets, strategy, universe  # noqa: E402

CFG = dict(
    start="2015-01-01",
    leverage=2.5,
    financing_bps=500.0,
    trend_ma=200,
    trend_scale=0.5,
    rebalance_mode="calendar",
    exec_price="open",
)
YEARS = list(range(2015, 2027))


def main() -> None:
    rows = []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        if name != "US":
            universe.canonical = lambda t: t
        mkt = strategy.Market(panel, mem, strategy.Config(**CFG))
        res = backtest.run(mkt)
        spy = backtest.spy_result(mkt)
        row = {"market": name, "label": markets.MARKETS[name]["label"]}
        for y in YEARS:
            b = res.equity.loc[str(y)]
            s = spy.equity.loc[str(y)]
            if len(b) < 3:
                row[y] = float("nan")
                continue
            row[y] = (b.iloc[-1] / b.iloc[0] - 1) - (s.iloc[-1] / s.iloc[0] - 1)
        rows.append(row)
    df = pd.DataFrame(rows).set_index("market")
    df.to_csv(ROOT / "results" / "yearly.csv")

    vals = df[YEARS]
    wins = (vals > 0).sum(axis=1)
    lines = [
        "# Year by year: bot minus index, shipped config",
        "",
        "Percentage-point difference in calendar-year return, 2.5x / daily 200-day cut /",
        "month-end / next open, 10 bps. Positive = bot beat that market's index.",
        "",
        "Generated by `uv run python scripts/yearly.py`.",
        "",
        "| market | " + " | ".join(str(y) for y in YEARS) + " | wins |",
        "|---|" + "---:|" * len(YEARS) + "---:|",
    ]
    for name, r in df.iterrows():
        cells = []
        for y in YEARS:
            v = r[y]
            cells.append("—" if pd.isna(v) else f"{v * 100:+.0f}")
        lines.append(
            f"| {r['label']} | "
            + " | ".join(cells)
            + f" | {int(wins[name])}/{len(YEARS)} |"
        )
    lines += [
        "",
        "## Per-year breadth",
        "",
        "| year | markets beating index | median diff |",
        "|---|---:|---:|",
    ]
    for y in YEARS:
        col = vals[y].dropna()
        lines.append(
            f"| {y} | {int((col > 0).sum())}/{len(col)} | {col.median() * 100:+.1f} pp |"
        )
    lines += [
        "",
        f"All cells: **{int((vals > 0).sum().sum())}/{int(vals.notna().sum().sum())}** "
        "market-years beat the local index.",
    ]
    (ROOT / "results" / "yearly.md").write_text("\n".join(lines) + "\n")

    print(lines[-1])
    for y in YEARS:
        col = vals[y].dropna()
        print(
            f"{y}: {int((col > 0).sum())}/{len(col)} markets, median {col.median() * 100:+.1f} pp"
        )
    print("wrote results/yearly.md")


if __name__ == "__main__":
    main()
