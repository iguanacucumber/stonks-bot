"""Robustness check for the 42-day rebalance signal.

Neighbor cadences, all-year returns, and a 21-day block bootstrap. See
results/cadence.md for the pre-registered acceptance criteria.

Run: uv run python scripts/cadence_check.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from bot import backtest, france, markets, strategy, universe  # noqa: E402
from scripts.france import BASE  # noqa: E402

YEARS = list(range(2015, 2027))


def bootstrap(rets: np.ndarray, block: int = 21, n: int = 1000, seed: int = 7):
    rng = np.random.default_rng(seed)
    m = len(rets)
    nb = int(np.ceil(m / block))
    finals = np.empty(n)
    dds = np.empty(n)
    for k in range(n):
        starts = rng.integers(0, m, nb)
        idx = (starts[:, None] + np.arange(block)[None, :]).ravel() % m
        path = np.cumprod(1.0 + rets[idx][:m])
        finals[k] = path[-1]
        peak = np.maximum.accumulate(path)
        dds[k] = (path / peak - 1.0).min()
    return finals, dds


def annual(eq: pd.Series) -> dict[int, float]:
    out = {}
    for y in YEARS:
        e = eq.loc[str(y)]
        out[y] = float(e.iloc[-1] / e.iloc[0] - 1.0) if len(e) > 2 else float("nan")
    return out


def main() -> None:
    panel, mem = markets.build("TECH")
    universe.canonical = lambda t: t
    kw = dict(BASE)
    kw.update(france.kwargs("TECH", "Interactive Brokers", "cto", 10000, panel))
    results = {}
    for days in (28, 35, 42, 49, 56, 63):
        cfg = strategy.Config(**{**kw, "rebalance_mode": "days", "rebalance_days": days})
        res = backtest.run(strategy.Market(panel, mem, cfg))
        f = france.after_tax(res, 10000, "TECH")
        results[days] = (res, f)
        print(
            f"{days:2d}d after {f['after_tax_eur']/10000:6.2f}x  "
            f"maxDD {f['maxdd']:6.1%}  trades {f['trades']}"
        )

    # monthly baseline for the annual table
    cfg = strategy.Config(**kw)
    base_res = backtest.run(strategy.Market(panel, mem, cfg))
    base_f = france.after_tax(base_res, 10000, "TECH")
    base_y = annual(base_res.equity)
    y42 = annual(results[42][0].equity)

    lines = ["", "## Robustness results", "", "| days | after tax | maxDD | trades |", "|---:|---:|---:|---:|"]
    for days, (_, f) in results.items():
        lines.append(
            f"| {days} | **{f['after_tax_eur']/10000:.2f}x** | {f['maxdd']:.1%} | {f['trades']} |"
        )
    lines += [
        "",
        "| year | monthly | 42d | diff |",
        "|---:|---:|---:|---:|",
    ]
    for y in YEARS:
        if pd.notna(base_y[y]) and pd.notna(y42[y]):
            lines.append(
                f"| {y} | {base_y[y]:.1%} | {y42[y]:.1%} | "
                f"{(y42[y]-base_y[y])*100:+.1f} pp |"
            )

    lines += ["", "| variant | p5 | median | p5 maxDD |", "|---|---:|---:|---:|"]
    for label, res in (("monthly", base_res), ("42d", results[42][0])):
        rets = res.equity.pct_change().dropna().to_numpy()
        finals, dds = bootstrap(rets)
        lines.append(
            f"| {label} | {np.quantile(finals, 0.05):.2f}x | "
            f"{np.median(finals):.2f}x | {np.quantile(dds, 0.05):.1%} |"
        )
    lines += ["", "Generated by `uv run python scripts/cadence_check.py`."]
    with open(ROOT / "results" / "cadence.md", "a") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote results/cadence.md")


if __name__ == "__main__":
    main()
