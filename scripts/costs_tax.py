"""After-tax cost check across the nine stock-level markets.

The tax profile (core-only, 10% leverage band, HIFO lots) is the taxable-account
product. This re-prices it and the monthly sleeve at 10/30/50 bps per side with a
37% tax on realized gains.

Run: uv run python scripts/costs_tax.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from bot import backtest, markets, strategy, universe  # noqa: E402

BASE = dict(
    start="2015-01-01",
    leverage=2.5,
    financing_bps=500.0,
    trend_ma=200,
    trend_scale=0.5,
    rebalance_mode="calendar",
    exec_price="open",
    tax_rate=0.37,
)
PROFILES = {
    "monthly": dict(core_mode="relative"),
    "tax": dict(core_mode="always", leverage_band=0.30, tax_lots="hifo"),
}
COSTS = (10.0, 30.0, 50.0)


def run(panel, mem, bps, kw):
    cfg = strategy.Config(**BASE, cost_bps=bps, **kw)
    mkt = strategy.Market(panel, mem, cfg)
    res = backtest.run(mkt)
    return 10000 * res.equity.iloc[-1]


def main() -> None:
    rows = []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        if name != "US":
            universe.canonical = lambda t: t
        row = {"market": name, "label": markets.MARKETS[name]["label"]}
        for label, kw in PROFILES.items():
            for bps in COSTS:
                row[f"{label}_{int(bps)}"] = run(panel, mem, bps, kw)
        rows.append(row)
    df = pd.DataFrame(rows)
    df.to_csv(ROOT / "results" / "costs_tax.csv", index=False)

    lines = [
        "# After-tax, after-cost: nine stock-level markets",
        "",
        "Shipped 2.5x / daily 200-day cut / month-end / next open, **37% tax on realized",
        "gains**, 10/30/50 bps per side. `monthly` is the full sleeve; `tax` is the",
        "core-only, 30% band, HIFO-lot profile. The tax profile ignores the local\nuniverse, so euro-area rows share the same EUR-converted core path.",
        "",
        "Generated by `uv run python scripts/costs_tax.py`.",
        "",
        "| market | monthly 10 | monthly 30 | monthly 50 | tax 10 | tax 30 | tax 50 |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r['label']} | ${r['monthly_10']:,.0f} | ${r['monthly_30']:,.0f} | "
            f"${r['monthly_50']:,.0f} | ${r['tax_10']:,.0f} | ${r['tax_30']:,.0f} | "
            f"${r['tax_50']:,.0f} |"
        )
    wins = (
        (df["tax_10"] > df["monthly_10"])
        & (df["tax_30"] > df["monthly_30"])
        & (df["tax_50"] > df["monthly_50"])
    ).sum()
    lines += [
        "",
        f"Tax profile beats the monthly sleeve at all three costs in **{wins}/9** markets.",
        f"Tax profile profitable at 50 bps in **{int((df['tax_50'] > 10000).sum())}/9** markets.",
    ]
    (ROOT / "results" / "costs_tax.md").write_text("\n".join(lines) + "\n")

    assert (df["tax_50"] > 10000).all(), "tax profile unprofitable at 50 bps"
    print(df.round(0).to_string(index=False))
    print(f"tax beats monthly at 10/30/50: {wins}/9")
    print("tax profile > $10k at 50 bps: 9/9")
    print("wrote results/costs_tax.md")


if __name__ == "__main__":
    main()
