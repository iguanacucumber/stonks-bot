"""Does the stock sleeve beat random 6-name portfolios in each market?

Sleeve only (no core), 1x, month-end, next open, 10 bps, sector cap off so the
comparison is identical in every market. For each market: the momentum sleeve,
equal weight, and 10 random 6-name portfolios from the same universe.

Run: uv run python scripts/quantile.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from bot import backtest, markets, strategy, universe  # noqa: E402

CFG = dict(
    start="2015-01-01",
    leverage=1.0,
    trend_ma=0,
    rebalance_mode="calendar",
    exec_price="open",
    core_weight=0.0,
    sector_cap=1.0,
    top_n=6,
    cost_bps=10.0,
)
SEEDS = range(10)


def stats(mkt, selector=None):
    res = backtest.run(mkt, selector=selector) if selector else backtest.run(mkt)
    m, _ = backtest.summarize(res, mkt)
    return m


def main() -> None:
    rows = []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        if name != "US":
            universe.canonical = lambda t: t
        mkt = strategy.Market(panel, mem, strategy.Config(**CFG))
        sleeve = stats(mkt)
        eq = stats(mkt, backtest.equal_weight_selector)
        rnd = pd.DataFrame([stats(mkt, backtest.random_selector(s, 6)) for s in SEEDS])
        pct = float((rnd["cagr"] < sleeve["cagr"]).mean())
        rows.append(
            {
                "market": name,
                "label": markets.MARKETS[name]["label"],
                "sleeve": sleeve["cagr"],
                "equal": eq["cagr"],
                "random_p50": rnd["cagr"].median(),
                "random_p5": rnd["cagr"].quantile(0.05),
                "random_p95": rnd["cagr"].quantile(0.95),
                "percentile": pct,
                "sleeve_dd": sleeve["max_dd"],
            }
        )
    df = pd.DataFrame(rows)
    df.to_csv(ROOT / "results" / "quantile.csv", index=False)

    lines = [
        "# Does the sleeve pick stocks, or just hold beta?",
        "",
        "Sleeve only (no core), 1x, month-end, next open, 10 bps, sector cap off.",
        "The null is 10 random 6-name portfolios from the same universe, same rules.",
        "",
        "Generated by `uv run python scripts/quantile.py`.",
        "",
        "| market | sleeve CAGR | equal weight | random median | p5 / p95 | sleeve percentile |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r['label']} | {r['sleeve']:.1%} | {r['equal']:.1%} | "
            f"{r['random_p50']:.1%} | {r['random_p5']:.1%} / {r['random_p95']:.1%} | "
            f"{r['percentile']:.0%} |"
        )
    med = float(df["percentile"].median())
    beats_eq = int((df["sleeve"] > df["equal"]).sum())
    beats_rnd = int((df["percentile"] > 0.5).sum())
    lines += [
        "",
        f"Median sleeve percentile: **{med:.0%}** of random 6-name portfolios.",
        f"Sleeve beats equal weight in **{beats_eq}/9** markets.",
        "",
        f"The sleeve beats the random median in **{beats_rnd}/9** markets. The momentum",
        "ranking is not pure noise in this sample, but it still loses to equal weight in",
        "France and Switzerland, and its 6-20% CAGR is far below the SMH core. The shipped",
        "book's return remains dominated by the core and the daily trend cut; the sleeve",
        "is a secondary source, not the engine.",
    ]
    (ROOT / "results" / "quantile.md").write_text("\n".join(lines) + "\n")
    print(df.round(3).to_string(index=False))
    print(f"median sleeve percentile {med:.0%}; beats equal weight {beats_eq}/9")
    print("wrote results/quantile.md")


if __name__ == "__main__":
    main()
