"""The HIFO tax profile across every stock-level market.

Compares the monthly sleeve with the taxable profile (core only, 10% leverage band,
HIFO lots) at 37% federal tax, in local currency.

Run: uv run python scripts/tax_markets.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pandas as pd  # noqa: E402

from bot import backtest, markets, strategy, universe  # noqa: E402

BASE = dict(
    start="2015-01-01",
    leverage=2.5,
    financing_bps=500.0,
    trend_ma=200,
    trend_scale=0.5,
    cost_bps=10.0,
)
PROFILES = {
    "monthly sleeve": {},
    "tax profile": {"core_mode": "always", "leverage_band": 0.10, "tax_lots": "hifo"},
}


def one(panel, mem, tax_rate, **kw):
    cfg = strategy.Config(tax_rate=tax_rate, **BASE, **kw)
    mkt = strategy.Market(panel, mem, cfg)
    res = backtest.run(mkt)
    m, _ = backtest.summarize(res, mkt)
    eq = res.equity
    r = eq.pct_change().dropna()
    w = eq.pct_change(5).dropna()
    return {
        "final": 10000 * eq.iloc[-1],
        "cagr": m["cagr"],
        "dd": m["max_dd"],
        "turnover": m["turnover_ann"],
        "mean1d": r.mean(),
        "mean5d": w.mean(),
    }


def main():
    rows = []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        if name != "US":
            universe.canonical = lambda t: t
        row = {"market": name, "label": markets.MARKETS[name]["label"]}
        for pname, pkw in PROFILES.items():
            pre = one(panel, mem, 0.0, **pkw)
            post = one(panel, mem, 0.37, **pkw)
            tag = "m" if pname == "monthly sleeve" else "t"
            row[f"{tag}_pre"] = pre["final"]
            row[f"{tag}_post"] = post["final"]
            row[f"{tag}_turn"] = pre["turnover"]
            row[f"{tag}_1d"] = post["mean1d"]
            row[f"{tag}_5d"] = post["mean5d"]
        rows.append(row)
    df = pd.DataFrame(rows)
    df["tax_wins"] = df["t_post"] > df["m_post"]
    assert (df.m_post > 10000).all(), "monthly sleeve unprofitable after tax"
    assert (df.t_post > 10000).all(), "tax profile unprofitable after tax"

    lines = [
        "# HIFO tax profile across markets",
        "",
        "Generated by `uv run python scripts/tax_markets.py`. $10,000, 2015-2026,",
        "2.5x, daily 200-day cut, 37% federal tax on realized gains, local currency.",
        "The taxable profile is core-only with a 10% leverage band and HIFO lots.",
        "",
        "| market | sleeve pre | sleeve after | tax profile after | tax turnover | sleeve 1d/5d after | tax 1d/5d after | tax wins |",
        "|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r.label} | ${r.m_pre:,.0f} | ${r.m_post:,.0f} | **${r.t_post:,.0f}** | "
            f"{r.t_turn:.1f}x | {r.m_1d:+.3%} / {r.m_5d:+.3%} | "
            f"{r.t_1d:+.3%} / {r.t_5d:+.3%} | {'yes' if r.tax_wins else 'no'} |"
        )
    lines += [
        "",
        f"Tax profile wins after tax in **{int(df.tax_wins.sum())}/{len(df)}** markets.",
        "It is core-only, so the USD/GBP/CHF rows share the same local-currency path;",
        "the difference between markets is the currency and the benchmark, not stock",
        "selection. The sleeve only wins where its local momentum beat the semis core",
        "enough to overcome the extra tax.",
        "",
        "Paper only. No orders, no broker, no keys.",
        "",
    ]
    out = Path(__file__).resolve().parent.parent / "results" / "tax_markets.md"
    out.write_text("\n".join(lines))
    print(df.round(4).to_string(index=False))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
