"""Start-date robustness of the US monthly best book, after French tax.

7 five-year windows (yearly starts 2015-2021), US monthly, 2.5x, SMH core,
IBKR 2 bps, French CTO 31.4%. Benchmark SPY after the same tax + EUR.

Run: uv run python scripts/us_robustness.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from bot import backtest, france, markets, strategy  # noqa: E402
from scripts.france import BASE  # noqa: E402

STARTS = [f"{y}-01-01" for y in range(2015, 2022)]


def main() -> None:
    panel, mem = markets.build("US")
    kw = dict(BASE)
    kw.pop("start", None)
    kw.update(france.kwargs("US", "Interactive Brokers", "cto", 10000, panel))
    rows = []
    for s in STARTS:
        end = min(pd.Timestamp(s) + pd.DateOffset(years=5), panel["date"].max())
        cfg = strategy.Config(start=s, end=str(end.date()), **kw)
        mkt = strategy.Market(panel, mem, cfg)
        res = backtest.run(mkt)
        f = france.after_tax(res, 10000, "US")
        spy = backtest.spy_result(mkt)
        gain = float(spy.equity.iloc[-1] / spy.equity.iloc[0] - 1.0)
        fx = france.fx_factor("US", spy.equity.index[0], spy.equity.index[-1])
        bench = (1.0 + max(0.0, gain) * 0.686) * fx
        rows.append(
            {
                "start": s[:4],
                "bot": f["after_tax_eur"] / 10000,
                "bench": bench,
                "gap": f["after_tax_eur"] / 10000 - bench,
                "maxdd": f["maxdd"],
            }
        )
        print(
            f"{s[:4]} after {rows[-1]['bot']:6.2f}x  SPY {bench:5.2f}x  "
            f"maxDD {rows[-1]['maxdd']:6.1%}"
        )
    df = pd.DataFrame(rows)
    win = float((df.bot > df.bench).mean())
    lines = [
        "# US monthly after tax: 5-year start-date robustness",
        "",
        "US monthly, 2.5x, SMH core, HIFO, IBKR 2 bps, French CTO 31.4%,",
        "5 bps spread. Benchmark SPY after the same tax and EUR translation.",
        "",
        f"**{int(win * len(df))}/{len(df)} windows beat SPY after tax ({win:.0%}).**",
        f"Median **{df['bot'].median():.2f}x** vs SPY **{df['bench'].median():.2f}x**; "
        f"worst {df['bot'].min():.2f}x; p5 {df['bot'].quantile(0.05):.2f}x.",
        "",
        "| start | US after tax | SPY after tax | gap | maxDD |",
        "|---|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r['start']} | **{r['bot']:.2f}x** | {r['bench']:.2f}x | "
            f"{r['gap']:+.2f}x | {r['maxdd']:.0%} |"
        )
    lines += ["", "Generated by `uv run python scripts/us_robustness.py`."]
    (ROOT / "results" / "us_robustness.md").write_text("\n".join(lines) + "\n")
    print(
        f"{int(win * len(df))}/{len(df)} beat SPY; median "
        f"{df['bot'].median():.2f}x vs {df['bench'].median():.2f}x"
    )
    print("wrote results/us_robustness.md")


if __name__ == "__main__":
    main()
