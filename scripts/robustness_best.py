"""Start-date robustness of the best French book+broker, after tax.

TECH monthly 2.5x, SMH core, Interactive Brokers (2 bps FX), French CTO 31.4%,
5 bps spread. 84 five-year windows, monthly starts 2015-2021. Compares the
after-tax EUR terminal with a buy-and-hold QQQ after the same CTO tax and FX.

Run: uv run python scripts/robustness_best.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from bot import backtest, france, markets, strategy  # noqa: E402

BASE = dict(
    leverage=2.5,
    financing_bps=500.0,
    trend_ma=200,
    trend_scale=0.5,
    rebalance_mode="calendar",
    exec_price="open",
    cost_bps=5.0,
    tax_lots="hifo",
)
STARTS = pd.date_range("2015-01-01", "2021-12-01", freq="MS")


def bootstrap(rets: np.ndarray, block: int = 21, n: int = 1000, seed: int = 11):
    rng = np.random.default_rng(seed)
    m = len(rets)
    nb = int(np.ceil(m / block))
    finals = np.empty(n)
    dds = np.empty(n)
    for k in range(n):
        starts = rng.integers(0, m, nb)
        idx = (starts[:, None] + np.arange(block)[None, :]).ravel() % m
        path = np.cumprod(1.0 + rets[idx][:m])
        finals[k] = path[-1]
        peak = np.maximum.accumulate(path)
        dds[k] = (path / peak - 1.0).min()
    return finals, dds


def main() -> None:
    panel, mem = markets.build("TECH")
    kw = dict(BASE)
    kw.update(france.kwargs("TECH", "Interactive Brokers", "cto", 10000, panel))
    dates = pd.DatetimeIndex(panel["date"].drop_duplicates().sort_values())
    rows = []
    for i, s in enumerate(STARTS):
        s0 = dates[dates >= s]
        if len(s0) == 0:
            continue
        start = s0[0]
        end = min(start + pd.DateOffset(years=5), dates[-1])
        cfg = strategy.Config(start=str(start.date()), end=str(end.date()), **kw)
        mkt = strategy.Market(panel, mem, cfg)
        res = backtest.run(mkt)
        f = france.after_tax(res, 10000, "TECH")
        spy = backtest.spy_result(mkt)
        fx = france.fx_factor("TECH", spy.equity.index[0], spy.equity.index[-1])
        gain = float(spy.equity.iloc[-1] / spy.equity.iloc[0] - 1.0)
        bench = (1.0 + max(0.0, gain) * (1.0 - 0.314)) * fx
        rows.append(
            {
                "start": str(start.date()),
                "bot": f["after_tax_eur"] / 10000,
                "bench": bench,
                "gap": f["after_tax_eur"] / 10000 - bench,
                "maxdd": f["maxdd"],
            }
        )
        if (i + 1) % 12 == 0:
            print(f"  {i + 1}/{len(STARTS)} windows", flush=True)

    df = pd.DataFrame(rows)
    df.to_csv(ROOT / "results" / "robustness_best.csv", index=False)
    win = float((df["bot"] > df["bench"]).mean())

    full_cfg = strategy.Config(start="2015-01-01", **kw)
    full = backtest.run(strategy.Market(panel, mem, full_cfg))
    rets = full.equity.pct_change().dropna().to_numpy()
    finals, dds = bootstrap(rets)

    lines = [
        "# Best French book: start-date robustness, after tax",
        "",
        "TECH monthly, 2.5x, SMH core, Interactive Brokers 2 bps FX, French CTO",
        "31.4% PFU, 5 bps spread, HIFO. 84 five-year windows (monthly starts",
        "2015-2021). Benchmark: QQQ buy-and-hold after the same 31.4% tax and",
        "EUR translation; broker tickets ignored (negligible for one entry/exit).",
        "",
        f"**{int(win * len(df))}/{len(df)} windows beat QQQ after tax ({win:.0%}).**",
        f"Median bot **{df['bot'].median():.2f}x** vs QQQ **{df['bench'].median():.2f}x**; "
        f"worst bot {df['bot'].min():.2f}x; p5 bot {df['bot'].quantile(0.05):.2f}x.",
        "",
        "| start | bot after tax | QQQ after tax | gap | maxDD |",
        "|---|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r['start']} | {r['bot']:.2f}x | {r['bench']:.2f}x | "
            f"{r['gap']:+.2f}x | {r['maxdd']:.0%} |"
        )
    lines += [
        "",
        "## Full-window bootstrap",
        "",
        f"- Full after-tax multiple: **{france.after_tax(full, 10000, 'TECH')['after_tax_eur'] / 10000:.2f}x**",
        f"- Block bootstrap p5: **{np.quantile(finals, 0.05):.2f}x**, median "
        f"**{np.median(finals):.2f}x**",
        f"- p5 max drawdown: **{np.quantile(dds, 0.05):.1%}**",
        "",
        "Generated by `uv run python scripts/robustness_best.py`.",
    ]
    (ROOT / "results" / "robustness_best.md").write_text("\n".join(lines) + "\n")
    print(
        f"{int(win * len(df))}/{len(df)} windows beat QQQ; "
        f"median {df['bot'].median():.2f}x vs {df['bench'].median():.2f}x; "
        f"bootstrap p5 {np.quantile(finals, 0.05):.2f}x"
    )
    print("wrote results/robustness_best.md and .csv")


if __name__ == "__main__":
    main()
