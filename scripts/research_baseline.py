"""Reproduce the shipped baselines with the Alpha Lab cost wrapper.

Run: uv run python scripts/research_baseline.py
Writes results/alpha_baseline.md.

Every row is labelled explicitly:
  * headline = USD-native after tax, translated at terminal FX;
  * div-tax adj = headline minus tax on gross distributions;
  * EUR ledger = annual EUR tax-lot replay (the real-life number).
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from bot.research.costs import CostModel  # noqa: E402
from bot.research.metrics import (  # noqa: E402
    annual_return,
    format_multiple,
    format_pct,
    worst_12m,
)
from scripts.research_common import (  # noqa: E402
    buy_hold,
    five_year_table,
    tech_baseline,
    us_baseline,
    write_report,
)


def row(name: str, v: dict) -> dict:
    eq = v["equity"]
    return {
        "name": name,
        "headline": v["after_tax_multiple"],
        "divadj": v["after_tax_multiple_divadj"],
        "ledger": v["ledger_multiple"],
        "ledger_div": v["ledger_multiple_divadj"],
        "cagr": v["summary"]["cagr"],
        "maxdd": v["maxdd"],
        "y2018": annual_return(eq, 2018),
        "y2022": annual_return(eq, 2022),
        "worst12": worst_12m(eq),
        "trades": v["trades"],
    }


def main() -> None:
    cm = CostModel()
    cm2 = cm.scaled(2.0)
    tech = tech_baseline(2.5, cm)
    tech2 = tech_baseline(2.5, cm2)
    us = us_baseline(2.5, cm)
    qqq = buy_hold("QQQ", cm)
    spy = buy_hold("SPY", cm)
    smh = buy_hold("SMH", cm)

    rows = [
        row("TECH 2.5x (shipped)", tech),
        row("TECH 2.5x @ 2x costs", tech2),
        row("US 2.5x (shipped, now default)", us),
        row("QQQ 1x", qqq),
        row("SPY 1x", spy),
        row("SMH 1x", smh),
    ]
    fy, fy_sum = five_year_table(tech["equity"], qqq["equity"], "TECH 2.5x", "QQQ")

    lines = [
        "# Alpha Lab baseline reproduction",
        "",
        "Generated by `uv run python scripts/research_baseline.py`.",
        "Bank €10,000, 2015-01-01 to 2026-11-25, French CTO at IBKR.",
        "**Headline** is USD-native after tax translated at terminal FX.",
        "**EUR ledger** replays the same USD trades with EUR cost basis and",
        "annual EUR tax: this is the real-life number, not the headline.",
        "MaxDD is the pre-tax daily path, consistent with existing reports.",
        "",
        "| book | headline | div-tax adj | EUR ledger | ledger+div | CAGR | maxDD | 2018 | 2022 | worst 12m | trades |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        lines.append(
            f"| {r['name']} | {format_multiple(r['headline'])} | "
            f"{format_multiple(r['divadj'])} | **{format_multiple(r['ledger'])}** | "
            f"{format_multiple(r['ledger_div'])} | {format_pct(r['cagr'])} | "
            f"{format_pct(r['maxdd'])} | {format_pct(r['y2018'])} | "
            f"{format_pct(r['y2022'])} | {format_pct(r['worst12'])} | "
            f"{r['trades']} |"
        )
    lines += [
        "",
        "## 2x-cost sensitivity",
        "",
        f"- TECH 2.5x headline: {tech['after_tax_multiple']:.2f}x -> "
        f"{tech2['after_tax_multiple']:.2f}x at 2x costs "
        f"({tech2['after_tax_multiple'] / tech['after_tax_multiple'] - 1:+.1%}).",
        f"- TECH EUR ledger: {tech['ledger_multiple']:.2f}x -> "
        f"{tech2['ledger_multiple']:.2f}x.",
        f"- TECH maxDD: {tech['maxdd']:.1%} -> {tech2['maxdd']:.1%}.",
        "",
        "## Five-year windows: TECH 2.5x vs QQQ (headline path)",
        "",
        fy,
        "",
        "## Reading",
        "",
        f"- TECH reproduces at **{tech['after_tax_multiple']:.2f}x headline / "
        f"{tech['ledger_multiple']:.2f}x EUR ledger**; the gap is annual EUR tax",
        "  and FX cost basis, not a strategy change.",
        f"- US monthly is the primary real-life book: **"
        f"{us['after_tax_multiple']:.2f}x headline / {us['ledger_multiple']:.2f}x",
        f"  EUR ledger**, maxDD {us['ledger_maxdd']:.1%} on the ledger. The 72.04x number that",
        "  appeared in an earlier draft was a broken canonical-symbol state; it is",
        "  fixed here. Do not quote 72.04x.",
        f"- QQQ is **{qqq['after_tax_multiple']:.2f}x headline / "
        f"{qqq['ledger_multiple']:.2f}x EUR ledger**. Any long-horizon",
        "  candidate has to clear the EUR-ledger bar, not just headline.",
        "- The dividend-tax column is the missing tax on gross distributions. It",
        "  is small for SMH (~0.1-0.3%/yr in this book) and material for bond/cash",
        "  ETFs; cross-asset reports use the adjusted number.",
        "- 2x costs are the gate, not a footnote: the fixed IBKR ticket and the",
        "  PFU are unchanged, only the bps frictions and financing double.",
        "",
    ]
    write_report(ROOT / "results" / "alpha_baseline.md", "\n".join(lines))
    print(
        f"TECH {tech['after_tax_multiple']:.2f}x headline / {tech['ledger_multiple']:.2f}x ledger"
    )
    print(f"TECH 2x-cost {tech2['after_tax_multiple']:.2f}x headline")
    print(
        f"US {us['after_tax_multiple']:.2f}x headline / {us['ledger_multiple']:.2f}x ledger"
    )
    print(
        f"QQQ {qqq['after_tax_multiple']:.2f}x headline / {qqq['ledger_multiple']:.2f}x ledger"
    )
    print("wrote results/alpha_baseline.md")


if __name__ == "__main__":
    main()
