"""How much of the bot should a real portfolio hold?

Blend the shipped book's daily returns with SPY, rebalanced daily, and report
CAGR, Sharpe and max drawdown for each weight.

Run: uv run python scripts/allocation.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from bot import backtest, markets, strategy  # noqa: E402


def main():
    panel, mem = markets.build("US")
    cfg = strategy.Config(
        leverage=2.5, financing_bps=500.0, trend_ma=200, trend_scale=0.5
    )
    mkt = strategy.Market(panel, mem, cfg)
    bot = backtest.run(mkt).equity.pct_change().dropna()
    spy = backtest.spy_result(mkt).equity.pct_change().dropna()
    j = bot.index.intersection(spy.index)
    b, s = bot.loc[j], spy.loc[j]
    corr = float(np.corrcoef(b, s)[0, 1])

    rows = []
    for w in np.arange(0.0, 1.01, 0.1):
        r = w * b + (1 - w) * s
        eq = (1 + r).cumprod()
        dd = float((eq / eq.cummax() - 1).min())
        cagr = float(eq.iloc[-1] ** (252 / len(r)) - 1)
        sharpe = float(r.mean() / r.std() * np.sqrt(252))
        rows.append({"bot_w": round(w, 2), "cagr": cagr, "sharpe": sharpe, "dd": dd})
    df = pd.DataFrame(rows)
    best = df.loc[df.sharpe.idxmax()]

    # monthly-rebalanced 50/50, to show the result is not a daily-rebalance artifact
    pair = pd.DataFrame({"b": b, "s": s})
    cur, vals, wgt = 1.0, [], 0.5
    for date, row in pair.iterrows():
        if date.day <= 3:
            wgt = 0.5
        cur *= 1.0 + (wgt * row["b"] + (1 - wgt) * row["s"])
        vals.append(cur)
    meq = pd.Series(vals, index=pair.index)
    er = meq.pct_change().dropna()
    m_cagr = meq.iloc[-1] ** (252 / len(er)) - 1
    m_sharpe = er.mean() / er.std() * np.sqrt(252)
    m_dd = (meq / meq.cummax() - 1).min()

    lines = [
        "# Allocation: bot + SPY",
        "",
        "Generated by `uv run python scripts/allocation.py`. Shipped book (SMH, 2.5x,",
        "daily 200-day cut) blended with SPY, rebalanced daily, 2015-2026, pre-tax.",
        f"Correlation of daily returns: **{corr:.2f}**; bot vol {b.std() * np.sqrt(252):.0%},",
        f"SPY vol {s.std() * np.sqrt(252):.0%}.",
        "",
        "| bot weight | CAGR | Sharpe | maxDD |",
        "|---|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        mark = " **<- best Sharpe**" if r.bot_w == best.bot_w else ""
        lines.append(
            f"| {r.bot_w:.0%}{mark} | {r.cagr:.1%} | {r.sharpe:.2f} | {r.dd:.1%} |"
        )
    lines += [
        "",
        "## Reading",
        "",
        f"- 100% bot maximizes money: {df.iloc[-1].cagr:.1%} CAGR, but a "
        f"{df.iloc[-1].dd:.0%} drawdown.",
        f"- {best.bot_w:.0%} bot / {1 - best.bot_w:.0%} SPY maximizes Sharpe "
        f"({best.sharpe:.2f}) at {best.cagr:.1%} CAGR and a {best.dd:.0%} drawdown.",
        "- The low correlation (0.66) is why: the bot is not just levered SPY.",
        "- Taxes are ignored here; the taxable variant of the bot (`--profile tax`) has",
        "  lower turnover and should be used in a taxable account before blending.",
        f"- Monthly rebalancing of the 50/50 blend gives {m_cagr:.1%} CAGR, Sharpe "
        f"{m_sharpe:.2f}, maxDD {m_dd:.1%}: the result is not a daily-rebalance artifact.",
        "",
        "Paper only. No orders, no broker, no keys.",
        "",
    ]
    out = Path(__file__).resolve().parent.parent / "results" / "allocation.md"
    out.write_text("\n".join(lines))
    print(df.round(3).to_string(index=False))
    print(f"\nbest Sharpe {best.sharpe:.3f} at {best.bot_w:.0%} bot")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
