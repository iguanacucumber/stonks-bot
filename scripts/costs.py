"""Do the 39 markets still beat their index after 30/50 bps per side?

The universal matrix runs at 1x with no trend cut so the market comparison is clean.
This script applies the *shipped* config (2.5x, daily 200d cut, month-end, next open)
and re-prices every market at 10, 30 and 50 bps.

Run: uv run python scripts/costs.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

import pandas as pd  # noqa: E402

from bot import backtest, markets  # noqa: E402
import universal as U  # noqa: E402

SHIPPED = dict(leverage=2.5, trend_ma=200, trend_scale=0.5)
COSTS = (10.0, 30.0, 50.0)


def tier1_rows() -> list[dict]:
    rows = []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        bench = U.benchmark(panel, mem)[0]
        bench_final = 10000 * bench.equity.iloc[-1]
        for bps in COSTS:
            res, m, _ = U.run(panel, mem, cost_bps=bps, **{k: v for k, v in {**U.CFG, **SHIPPED}.items() if k != "cost_bps"})
            final = 10000 * res.equity.iloc[-1]
            rows.append(
                {
                    "tier": 1,
                    "market": name,
                    "label": markets.MARKETS[name]["label"],
                    "bps": bps,
                    "final": final,
                    "index": bench_final,
                    "beat": final > bench_final,
                    "cagr": m["cagr"],
                    "dd": m["max_dd"],
                }
            )
    return rows


def tier2_rows() -> list[dict]:
    rows = []
    for code, etf in markets.COUNTRY_ETFS.items():
        panel, mem = markets.build_etf(etf)
        bench = U.benchmark(panel, mem)[0]
        bench_final = 10000 * bench.equity.iloc[-1]
        for bps in COSTS:
            res, m, _ = U.dual_run(panel, mem, cost_bps=bps, **{k: v for k, v in {**U.CFG, **SHIPPED}.items() if k != "cost_bps"})
            final = 10000 * res.equity.iloc[-1]
            rows.append(
                {
                    "tier": 2,
                    "market": code,
                    "label": markets.ETF_NAMES[etf],
                    "bps": bps,
                    "final": final,
                    "index": bench_final,
                    "beat": final > bench_final,
                    "cagr": m["cagr"],
                    "dd": m["max_dd"],
                }
            )
    return rows


def main() -> None:
    rows = tier1_rows() + tier2_rows()
    df = pd.DataFrame(rows)
    out = ROOT / "results" / "costs.csv"
    df.to_csv(out, index=False)

    lines = [
        "# Does the edge survive costs?",
        "",
        "The shipped config (2.5x, daily 200-day cut, month-end, next open) applied to",
        "every market at 10 / 30 / 50 bps per side. Benchmarks are each market's own",
        "total-return instrument. 10 bps is the backtest default; 30-50 bps covers",
        "spreads, impact and the French FTT.",
        "",
        "Generated by `uv run python scripts/costs.py`.",
        "",
        "| tier | markets | 10 bps beat | 30 bps beat | 50 bps beat |",
        "|---|---:|---:|---:|---:|",
    ]
    for tier in (1, 2):
        sub = df[df["tier"] == tier]
        cells = []
        for bps in COSTS:
            s = sub[sub["bps"] == bps]
            cells.append(f"{int(s['beat'].sum())}/{len(s)}")
        lines.append(
            f"| {tier} | {sub['market'].nunique()} | " + " | ".join(cells) + " |"
        )

    at50 = df[df["bps"] == 50.0]
    worst = at50.loc[(at50["final"] / at50["index"]).idxmin()]
    lines += [
        "",
        "## Worst market at 50 bps",
        "",
        f"**{worst['market']}** ({worst['label']}): bot ${worst['final']:,.0f} vs index "
        f"${worst['index']:,.0f} ({worst['final'] / worst['index'] - 1:+.1%}).",
        "",
        "## By market at 50 bps",
        "",
        "| market | bot | index | margin |",
        "|---|---:|---:|---:|",
    ]
    for _, r in at50.sort_values("market").iterrows():
        lines.append(
            f"| {r['market']} | ${r['final']:,.0f} | ${r['index']:,.0f} | "
            f"{r['final'] / r['index'] - 1:+.1%} |"
        )
    (ROOT / "results" / "costs.md").write_text("\n".join(lines) + "\n")

    for bps in COSTS:
        s = df[df["bps"] == bps]
        print(
            f"{bps:4.0f} bps: beat {int(s['beat'].sum())}/{len(s)}  "
            f"median margin {float((s['final'] / s['index'] - 1).median()):+.1%}"
        )
    print(f"worst @50: {worst['market']} {worst['final'] / worst['index'] - 1:+.1%}")
    print(f"wrote {out} and results/costs.md")


if __name__ == "__main__":
    main()
