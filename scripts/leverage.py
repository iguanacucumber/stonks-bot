"""Leverage ladder and the all-market check at the shipped configuration.

Shipped: 2.5x gross, 5%/yr margin, half size while the core is below its 200-day MA
(checked daily, executed at the next close).

Run: uv run python scripts/leverage.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import pandas as pd  # noqa: E402

import universal  # noqa: E402
from bot import backtest, data, markets, strategy, universe  # noqa: E402

LEV, FIN, TREND = 2.5, 500.0, 200
SCALE = 0.5
LADDER = [
    (1.0, 500.0, 0),
    (1.5, 500.0, 0),
    (2.0, 500.0, 0),
    (2.5, 500.0, 0),
    (2.5, 500.0, TREND),
    (3.0, 500.0, TREND),
]


def us_ladder(mem, panel) -> pd.DataFrame:
    rows = []
    for lev, fin, trend in LADDER:
        cfg = strategy.Config(
            start="2015-01-01",
            leverage=lev,
            financing_bps=fin,
            trend_ma=trend,
            trend_scale=SCALE,
        )
        mkt = strategy.Market(panel, mem, cfg)
        r = backtest.run(mkt)
        m, _ = backtest.summarize(r, mkt)
        eq = r.equity
        y22 = eq.loc["2022"].iloc[-1] / eq.loc["2022"].iloc[0] - 1
        rows.append(
            {
                "leverage": lev,
                "financing": fin,
                "trend": trend,
                "final": 10000 * eq.iloc[-1],
                "cagr": m["cagr"],
                "sharpe": m["sharpe"],
                "dd": m["max_dd"],
                "y2022": y22,
                "turnover": m["turnover_ann"],
            }
        )
    return pd.DataFrame(rows)


def markets_shipped() -> tuple[pd.DataFrame, pd.DataFrame]:
    t1, t2 = [], []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        if name != "US":
            universe.canonical = lambda t: t
        r, m, _ = universal.run(
            panel,
            mem,
            leverage=LEV,
            financing_bps=FIN,
            trend_ma=TREND,
            trend_scale=SCALE,
        )
        b, _, _ = universal.benchmark(panel, mem)
        t1.append(
            {
                "market": name,
                "label": markets.MARKETS[name]["label"],
                "final": 10000 * r.equity.iloc[-1],
                "bench": 10000 * b.equity.iloc[-1],
                "dd": m["max_dd"],
                "margin": r.equity.iloc[-1] / b.equity.iloc[-1] - 1,
            }
        )
    for code, etf in markets.COUNTRY_ETFS.items():
        panel, mem = markets.build_etf(etf)
        r, m, mkt = universal.dual_run(
            panel,
            mem,
            leverage=LEV,
            financing_bps=FIN,
            trend_ma=TREND,
            trend_scale=SCALE,
        )
        b = backtest.spy_result(mkt)
        t2.append(
            {
                "market": code,
                "label": markets.ETF_NAMES[etf],
                "final": 10000 * r.equity.iloc[-1],
                "bench": 10000 * b.equity.iloc[-1],
                "dd": m["max_dd"],
                "margin": r.equity.iloc[-1] / b.equity.iloc[-1] - 1,
            }
        )
    return pd.DataFrame(t1), pd.DataFrame(t2)


def main():
    mem = universe.load_membership()
    panel = data.build_panel(mem)
    lad = us_ladder(mem, panel)
    t1, t2 = markets_shipped()
    both = pd.concat([t1, t2], ignore_index=True)
    assert (both.final > 10000).all(), "a market is unprofitable"
    assert (both.final > both.bench).all(), "a market loses to its index"

    ship = lad[(lad.leverage == LEV) & (lad.trend == TREND)].iloc[0]
    base = lad[(lad.leverage == 1.0)].iloc[0]
    lines = [
        "# Leverage and the daily trend cut",
        "",
        "Generated by `uv run python scripts/leverage.py`. The shipped default is",
        f"**{LEV:.1f}x gross, financed at {FIN / 100:.1f}%/yr**, plus a daily check: while the",
        f"core is below its {TREND}-day MA, gross is cut to {SCALE:.0%} until it recovers.",
        "Interest, commissions and forced de-leveraging are all in the numbers.",
        "",
        "## US book, 2015-2026 ($10,000)",
        "",
        "| leverage | trend | final | CAGR | Sharpe | maxDD | 2022 | turnover |",
        "|---:|---|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in lad.iterrows():
        ship_mark = " **<- shipped**" if (r.leverage, r.trend) == (LEV, TREND) else ""
        trend = f"{int(r.trend)}d" if r.trend else "none"
        lines.append(
            f"| {r.leverage:.1f}x{ship_mark} | {trend} | **${r.final:,.0f}** | {r.cagr:.1%} | "
            f"{r.sharpe:.2f} | {r.dd:.1%} | {r.y2022:+.1%} | {r.turnover:.1f}x |"
        )
    lines += [
        "",
        f"1x makes **${base.final:,.0f}** with a {base.dd:.1%} drawdown. The shipped config",
        f"makes **${ship.final:,.0f}** ({ship.final / base.final:.1f}x) with a {ship.dd:.1%}",
        f"drawdown and {ship.y2022:+.1%} in 2022. The daily cut is what lets 2.5x carry",
        "roughly the same drawdown as plain 2x did before it: compare the 2.5x rows.",
        "Sharpe is still flat across leverage: the extra money is borrowed, not discovered.",
        "",
        f"## All {len(both)} markets at the shipped {LEV}x + trend",
        "",
        f"- Profitable: **{int((both.final > 10000).sum())}/{len(both)}**.",
        f"- Beats the local index: **{int((both.final > both.bench).sum())}/{len(both)}**.",
        f"- Median margin over the index: **{both.margin.median():+.0%}**.",
        f"- Weakest market: {both.loc[both.final.idxmin(), 'label']} at "
        f"${both.final.min():,.0f} vs ${both.loc[both.final.idxmin(), 'bench']:,.0f}.",
        f"- Worst drawdown: {both.dd.min():.1%} "
        f"({both.loc[both.dd.idxmin(), 'label']}).",
        "",
        "## Stock-level markets (shipped)",
        "",
        "| market | bot $ | index $ | margin | maxDD |",
        "|---|---:|---:|---:|---:|",
    ]
    for _, r in t1.iterrows():
        lines.append(
            f"| {r.label} | **${r.final:,.0f}** | ${r.bench:,.0f} | "
            f"{r.margin:+.0%} | {r.dd:.1%} |"
        )
    lines += [
        "",
        "## Caveats",
        "",
        "- **Drawdowns are not hypothetical.** The shipped book still loses ~60% peak to",
        "  trough in the sample. A real margin account needs maintenance margin and can be",
        "  liquidated; this model de-levers and halves instead of blowing up.",
        "- **Financing is assumed at 5%/yr**, the conservative middle of 2015-2026 rates.",
        "- **The trend cut is a risk tool, not alpha.** It improves the path (and on the",
        "  tech book, the terminal value) but it is one rule on one crash.",
        "- **Still one asset.** Leverage multiplies a semis ETF, not a diversified edge.",
        "- Paper only. No orders, no broker, no keys.",
        "",
        "## Verdict",
        "",
        f"Shipped: **${ship.final:,.0f}** from $10,000 at {LEV:.1f}x with a daily trend cut,",
        f"a {ship.dd:.1%} max drawdown, beat the local index in all {len(both)} markets.",
        "That is more money than plain 2x, with the same drawdown. The risk is still one",
        "industry and one decade.",
        "",
    ]
    out = Path(__file__).resolve().parent.parent / "results" / "leverage.md"
    out.write_text("\n".join(lines))
    print(lad.round(4).to_string(index=False))
    print(
        f"\n{len(both)} markets: profitable {(both.final > 10000).sum()}/{len(both)}, "
        f"beat index {(both.final > both.bench).sum()}/{len(both)}, "
        f"worst DD {both.dd.min():.1%}"
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
