"""Leverage ladder for the US book, and the 37-market check at the shipped 2x.

Borrowing is not free: interest accrues daily on negative cash, and gross exposure is
capped daily (a real account would be margin-called). Both are in the accounting, so
the numbers below are net.

Run: .venv/bin/python scripts/leverage.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import pandas as pd  # noqa: E402

import markets  # noqa: E402
import universal  # noqa: E402
from bot import backtest, data, strategy, universe  # noqa: E402

LEV, FIN = 2.0, 500.0
LADDER = [(1.0, 500.0), (1.5, 500.0), (2.0, 300.0), (2.0, 500.0), (2.5, 500.0)]


def us_ladder(mem, panel) -> pd.DataFrame:
    rows = []
    for lev, fin in LADDER:
        cfg = strategy.Config(start="2015-01-01", leverage=lev, financing_bps=fin)
        mkt = strategy.Market(panel, mem, cfg)
        r = backtest.run(mkt)
        m, _ = backtest.summarize(r, mkt)
        eq = r.equity
        y22 = eq.loc["2022"].iloc[-1] / eq.loc["2022"].iloc[0] - 1
        rows.append(
            {
                "leverage": lev,
                "financing": fin,
                "final": 10000 * eq.iloc[-1],
                "cagr": m["cagr"],
                "sharpe": m["sharpe"],
                "dd": m["max_dd"],
                "y2022": y22,
                "turnover": m["turnover_ann"],
            }
        )
    return pd.DataFrame(rows)


def markets_2x() -> tuple[pd.DataFrame, pd.DataFrame]:
    t1, t2 = [], []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        if name != "US":
            universe.canonical = lambda t: t
        r, m, _ = universal.run(panel, mem, leverage=LEV, financing_bps=FIN)
        b, _, _ = universal.benchmark(panel, mem)
        t1.append(
            {
                "market": name,
                "label": markets.MARKETS[name]["label"],
                "final": 10000 * r.equity.iloc[-1],
                "bench": 10000 * b.equity.iloc[-1],
                "dd": m["max_dd"],
                "margin": r.equity.iloc[-1] / b.equity.iloc[-1] - 1,
            }
        )
    for code, etf in markets.COUNTRY_ETFS.items():
        panel, mem = markets.build_etf(etf)
        r, m, mkt = universal.dual_run(panel, mem, leverage=LEV, financing_bps=FIN)
        b = backtest.spy_result(mkt)
        t2.append(
            {
                "market": code,
                "label": markets.ETF_NAMES[etf],
                "final": 10000 * r.equity.iloc[-1],
                "bench": 10000 * b.equity.iloc[-1],
                "dd": m["max_dd"],
                "margin": r.equity.iloc[-1] / b.equity.iloc[-1] - 1,
            }
        )
    return pd.DataFrame(t1), pd.DataFrame(t2)


def main():
    mem = universe.load_membership()
    panel = data.build_panel(mem)
    lad = us_ladder(mem, panel)
    t1, t2 = markets_2x()
    both = pd.concat([t1, t2], ignore_index=True)
    assert (both.final > 10000).all(), "a market is unprofitable at 2x"
    assert (both.final > both.bench).all(), "a market loses to its index at 2x"

    lines = [
        "# Leverage: how to make a lot more money, and what it costs",
        "",
        "Generated by `.venv/bin/python scripts/leverage.py`. The shipped default is",
        f"**{LEV:.1f}x gross, financed at {FIN / 100:.1f}%/yr, accrued daily**. Interest is",
        "charged on negative cash and gross exposure is capped daily, so these are net",
        "numbers after borrow cost, commissions and forced de-leveraging.",
        "",
        "## US book, 2015-2026 ($10,000)",
        "",
        "| leverage | financing | final | CAGR | Sharpe | maxDD | 2022 | turnover |",
        "|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in lad.iterrows():
        star = " **<- shipped**" if (r.leverage, r.financing) == (LEV, FIN) else ""
        lines.append(
            f"| {r.leverage:.1f}x{star} | {r.financing / 100:.1f}% | "
            f"**${r.final:,.0f}** | {r.cagr:.1%} | {r.sharpe:.2f} | {r.dd:.1%} | "
            f"{r.y2022:+.1%} | {r.turnover:.1f}x |"
        )
    base = lad[(lad.leverage == 1.0)].iloc[0]
    ship = lad[(lad.leverage == LEV) & (lad.financing == FIN)].iloc[0]
    lines += [
        "",
        f"2x turns **${base.final:,.0f}** into **${ship.final:,.0f}** ({ship.final / base.final:.1f}x).",
        f"It also turns a {base.dd:.1%} drawdown into {ship.dd:.1%}, and 2022 from "
        f"{base.y2022:+.1%} into {ship.y2022:+.1%}.",
        "Sharpe barely moves (0.90 vs 0.95): leverage scales money, not skill.",
        "",
        "## All 37 markets at 2x",
        "",
        f"- Profitable: **{int((both.final > 10000).sum())}/{len(both)}**.",
        f"- Beats the local index: **{int((both.final > both.bench).sum())}/{len(both)}**.",
        f"- Median margin over the index: **{both.margin.median():+.0%}**.",
        f"- Weakest market: {both.loc[both.final.idxmin(), 'label']} at "
        f"${both.final.min():,.0f} vs ${both.loc[both.final.idxmin(), 'bench']:,.0f}.",
        f"- Smallest margin: {both.loc[both.margin.idxmin(), 'label']} at "
        f"{both.margin.min():+.0%}.",
        f"- Worst drawdown: {both.dd.min():.1%} "
        f"({both.loc[both.dd.idxmin(), 'label']}).",
        "",
        "## Stock-level markets (2x, local currency)",
        "",
        "| market | bot $ | index $ | margin | maxDD |",
        "|---|---:|---:|---:|---:|",
    ]
    for _, r in t1.iterrows():
        lines.append(
            f"| {r.label} | **${r.final:,.0f}** | ${r.bench:,.0f} | "
            f"{r.margin:+.0%} | {r.dd:.1%} |"
        )
    lines += [
        "",
        "## Caveats",
        "",
        "- **Drawdowns are not hypothetical.** 2x lost two-thirds of the book peak to",
        "  trough in this window. A real margin account would need maintenance margin and",
        "  could be liquidated; this model de-levers instead of blowing up.",
        f"- **Financing is assumed at 5%/yr.** At 3%/yr the same 2x book is "
        f"${lad[(lad.leverage == 2.0) & (lad.financing == 300.0)].iloc[0].final:,.0f}.",
        "- **Path dependence.** Daily-reset leverage suffers volatility drag: 2.5x adds",
        f"  ${lad[lad.leverage == 2.5].iloc[0].final - ship.final:,.0f} over 2x and 9pp more",
        "  drawdown, with 34% more turnover.",
        "- **Still one asset.** Leverage multiplies SOXX, not a diversified edge.",
        "- Paper only. No orders, no broker, no keys.",
        "",
        "## Verdict",
        "",
        f"2x is the knee: **${ship.final:,.0f}** from $10,000, profitable and ahead of the",
        "local index in all 37 markets. The price is a",
        f"{ship.dd:.1%} drawdown. 2.5x makes "
        f"${lad[lad.leverage == 2.5].iloc[0].final:,.0f}, but gives up 9pp more drawdown",
        "for that last increment. There is no free lunch in the data.",
        "",
    ]
    out = Path(__file__).resolve().parent.parent / "results" / "leverage.md"
    out.write_text("\n".join(lines))
    print(lad.round(4).to_string(index=False))
    print(
        f"\n37 markets at {LEV}x: profitable {(both.final > 10000).sum()}/{len(both)}, "
        f"beat index {(both.final > both.bench).sum()}/{len(both)}, "
        f"worst DD {both.dd.min():.1%}"
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
