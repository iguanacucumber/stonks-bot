"""Pre-registered rebalance-cadence test at IBKR with French tax.

See results/cadence.md for the hypothesis and acceptance criteria. This script
only measures; it does not change defaults.

Run: uv run python scripts/cadence.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import pandas as pd  # noqa: E402

from bot import backtest, france, markets, strategy, universe  # noqa: E402
from scripts.france import BASE  # noqa: E402

VARIANTS = {
    "monthly": dict(rebalance_mode="calendar"),
    "bimonthly": dict(rebalance_mode="days", rebalance_days=42),
    "quarterly": dict(rebalance_mode="days", rebalance_days=63),
    "weekly": dict(
        rebalance_mode="days",
        rebalance_days=5,
        lookback=20,
        skip=2,
        core_lookback=20,
        vol_window=10,
    ),
    "daily": dict(
        rebalance_mode="days",
        rebalance_days=1,
        lookback=10,
        skip=1,
        core_lookback=10,
        vol_window=5,
    ),
}


def annual(eq: pd.Series, year: int) -> float:
    e = eq.loc[str(year)]
    return float(e.iloc[-1] / e.iloc[0] - 1.0) if len(e) > 2 else float("nan")


def main() -> None:
    panel, mem = markets.build("TECH")
    universe.canonical = lambda t: t
    kw = dict(BASE)
    kw.update(france.kwargs("TECH", "Interactive Brokers", "cto", 10000, panel))
    rows = []
    for name, extra in VARIANTS.items():
        cfg = strategy.Config(**{**kw, **extra})
        res = backtest.run(strategy.Market(panel, mem, cfg))
        f = france.after_tax(res, 10000, "TECH")
        rows.append(
            {
                "variant": name,
                "after_tax_x": f["after_tax_eur"] / 10000,
                "maxDD": f["maxdd"],
                "2018": annual(res.equity, 2018),
                "2022": annual(res.equity, 2022),
                "fees": f["fees_eur"],
                "tax_paid": f["tax_paid_eur"],
                "exit_tax": f["exit_tax_eur"],
                "trades": f["trades"],
            }
        )
        print(
            f"{name:9s} after {rows[-1]['after_tax_x']:6.2f}x  "
            f"maxDD {rows[-1]['maxDD']:6.1%}  2018 {rows[-1]['2018']:7.1%}  "
            f"2022 {rows[-1]['2022']:7.1%}  trades {rows[-1]['trades']}"
        )
    df = pd.DataFrame(rows)
    base = df[df.variant == "monthly"].iloc[0]
    lines = [
        "",
        "## Results",
        "",
        "| variant | after tax | maxDD | 2018 | 2022 | fees | tax paid | exit tax | trades |",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r['variant']} | **{r['after_tax_x']:.2f}x** | {r['maxDD']:.1%} | "
            f"{r['2018']:.1%} | {r['2022']:.1%} | €{r['fees']:,.0f} | "
            f"€{r['tax_paid']:,.0f} | €{r['exit_tax']:,.0f} | {int(r['trades'])} |"
        )
    winners = df[
        (df.after_tax_x > base.after_tax_x)
        & (df.maxDD >= base.maxDD - 0.02)
        & (df["2018"] >= base["2018"])
        & (df["2022"] >= base["2022"])
        & (df.variant != "monthly")
    ]
    if winners.empty:
        verdict = (
            "**No variant passes.** Keep the monthly calendar rebalance; faster "
            "cadence adds tax/fees without a consistent gain, slower cadence gives "
            "up more momentum than it saves in PFU."
        )
    else:
        verdict = (
            "**Initial pass:** "
            + ", ".join(winners.variant)
            + ". Run the pre-registered check (`scripts/cadence_check.py`) "
            "before adopting; neighbors must confirm."
        )
    lines += ["", verdict, "", "Generated by `uv run python scripts/cadence.py`."]
    with open(ROOT / "results" / "cadence.md", "a") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"\n{verdict}")
    print("wrote results/cadence.md")


if __name__ == "__main__":
    main()
