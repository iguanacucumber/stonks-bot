"""Is the result one lucky start date? Start-date sweep + block bootstrap.

1. Every month from 2015 to 2021, run 5 years of the shipped book and SPY.
2. Bootstrap the full-window daily returns in 10-day blocks to get a distribution
   of terminal wealth and max drawdown instead of one path.

Run: uv run python scripts/robustness.py
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

from bot import backtest, markets, strategy  # noqa: E402

BASE = dict(
    leverage=2.5,
    financing_bps=500.0,
    trend_ma=200,
    trend_scale=0.5,
    cost_bps=10.0,
    core="SMH",
)


def run_window(start: pd.Timestamp, end: pd.Timestamp):
    cfg = strategy.Config(start=str(start.date()), end=str(end.date()), **BASE)
    mkt = strategy.Market(*PANEL, cfg)
    bot = backtest.run(mkt)
    spy = backtest.spy_result(mkt)
    b = bot.equity.iloc[-1] / bot.equity.iloc[0] - 1
    s = spy.equity.iloc[-1] / spy.equity.iloc[0] - 1
    return b, s


def bootstrap(
    rets: np.ndarray, block: int, n: int, seed: int
) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    m = len(rets)
    nb = int(np.ceil(m / block))
    finals = np.empty(n)
    dds = np.empty(n)
    for k in range(n):
        starts = rng.integers(0, m, nb)
        idx = (starts[:, None] + np.arange(block)[None, :]).ravel() % m
        path = np.cumprod(1.0 + rets[idx][:m])
        finals[k] = path[-1]
        peak = np.maximum.accumulate(path)
        dds[k] = (path / peak - 1.0).min()
    return finals, dds


PANEL = markets.build("US")


def main():
    panel, mem = PANEL
    dates = panel["date"].drop_duplicates().sort_values().to_numpy()
    dates = pd.DatetimeIndex(dates)
    starts = pd.date_range("2015-01-01", "2021-12-01", freq="MS")
    rows = []
    for s in starts:
        s0 = dates[dates >= s]
        if len(s0) == 0:
            continue
        start = s0[0]
        end = min(start + pd.DateOffset(years=5), dates[-1])
        b, sp = run_window(start, end)
        rows.append({"start": str(start.date()), "bot": b, "spy": sp, "gap": b - sp})
    sweep = pd.DataFrame(rows)
    win = (sweep["bot"] > sweep["spy"]).mean()

    cfg = strategy.Config(
        start="2015-01-01",
        leverage=2.5,
        financing_bps=500.0,
        trend_ma=200,
        trend_scale=0.5,
        core="SMH",
    )
    mkt = strategy.Market(panel, mem, cfg)
    res = backtest.run(mkt)
    spy = backtest.spy_result(mkt)
    r = res.equity.pct_change().dropna().to_numpy()
    b = spy.equity.pct_change().dropna().to_numpy()
    finals, dds = bootstrap(r, 10, 2000, 7)
    sfinals, _ = bootstrap(b, 10, 2000, 11)
    p_beat = float((finals > sfinals).mean())
    p_dd50 = float((dds < -0.50).mean())

    lines = [
        "# Robustness: start dates and bootstrap",
        "",
        "Generated by `uv run python scripts/robustness.py`. Shipped book (SMH, 2.5x,",
        "daily 200-day cut), US, 10 bps.",
        "",
        "## 5-year windows, every month start",
        "",
        f"- Windows: **{len(sweep)}**, from {sweep.start.min()} to {sweep.start.max()}.",
        f"- Bot beats SPY in **{win:.0%}** of them.",
        f"- Median 5-year return: bot **{sweep.bot.median():+.0%}** vs SPY {sweep.spy.median():+.0%}.",
        f"- Worst bot window: {sweep.bot.min():+.0%} (SPY {sweep.loc[sweep.bot.idxmin(), 'spy']:+.0%}).",
        f"- Best bot window: {sweep.bot.max():+.0%}.",
        "",
        "| start | bot 5y | SPY 5y | gap |",
        "|---|---:|---:|---:|",
    ]
    for _, r_ in sweep.iterrows():
        lines.append(f"| {r_.start} | {r_.bot:+.0%} | {r_.spy:+.0%} | {r_.gap:+.0%} |")
    lines += [
        "",
        "## Block bootstrap (10-day blocks, 2000 paths)",
        "",
        "| | median | p5 | p95 |",
        "|---|---:|---:|---:|",
        f"| final wealth, bot | {np.median(finals):.2f}x | {np.quantile(finals, 0.05):.2f}x | {np.quantile(finals, 0.95):.2f}x |",
        f"| final wealth, SPY | {np.median(sfinals):.2f}x | {np.quantile(sfinals, 0.05):.2f}x | {np.quantile(sfinals, 0.95):.2f}x |",
        f"| max drawdown, bot | {np.median(dds):.0%} | {np.quantile(dds, 0.05):.0%} | {np.quantile(dds, 0.95):.0%} |",
        "",
        f"- P(bot final > SPY final) = **{p_beat:.0%}**.",
        f"- P(bot max drawdown worse than -50%) = **{p_dd50:.0%}**.",
        "- The bootstrap reuses one path's daily returns; it measures path risk, not",
        "  regime risk. The start-date sweep is the better test of the latter.",
        "",
    ]
    out = Path(__file__).resolve().parent.parent / "results" / "robustness.md"
    out.write_text("\n".join(lines))
    print(sweep.round(3).to_string(index=False))
    print(
        f"\nwin rate {win:.0%}; median bot {sweep.bot.median():+.0%} vs "
        f"SPY {sweep.spy.median():+.0%}"
    )
    print(
        f"bootstrap: median {np.median(finals):.2f}x, p5 {np.quantile(finals, 0.05):.2f}x, "
        f"P(beat SPY) {p_beat:.0%}, P(DD worse than -50%) {p_dd50:.0%}"
    )
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
