"""SOXX vs SMH as the core, across every stock-level market.

Run: uv run python scripts/core.py
Writes results/core.md.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pandas as pd  # noqa: E402

from bot import backtest, markets, strategy  # noqa: E402

BASE = dict(
    rebalance_mode="calendar",
    exec_price="open",
    start="2015-01-01",
    top_n=6,
    lookback=126,
    skip=10,
    vol_window=20,
    max_weight=0.06,
    sector_cap=1.0,
    gross=1.0,
    stop=1.0,
    regime_gross=1.0,
    core_weight=1.0,
    core_mode="relative",
    core_lookback=126,
    cost_bps=10.0,
)


def one(panel, mem, core, lev=1.0, matrix=True):
    if matrix:
        cfg = strategy.Config(leverage=lev, financing_bps=500.0, core=core, **BASE)
    else:
        # shipped config: 40% sector cap, 6-name sleeve
        cfg = strategy.Config(
            start="2015-01-01", leverage=lev, financing_bps=500.0, core=core
        )
    mkt = strategy.Market(panel, mem, cfg)
    res = backtest.run(mkt)
    m, _ = backtest.summarize(res, mkt)
    return 10000 * res.equity.iloc[-1], m


def main():
    rows = []
    for name in markets.MARKETS:
        panel, mem = markets.build(name)
        f_s, m_s = one(panel, mem, "SOXX")
        f_m, m_m = one(panel, mem, "SMH")
        rows.append(
            {
                "market": name,
                "label": markets.MARKETS[name]["label"],
                "soxx": f_s,
                "smh": f_m,
                "soxx_dd": m_s["max_dd"],
                "smh_dd": m_m["max_dd"],
                "soxx_sh": m_s["sharpe"],
                "smh_sh": m_m["sharpe"],
                "winner": "SMH" if f_m > f_s else "SOXX",
            }
        )
    df = pd.DataFrame(rows)
    for name in ("US", "TECH"):
        panel, mem = markets.build(name)
        s2, _ = one(panel, mem, "SOXX", 2.0, matrix=False)
        m2, _ = one(panel, mem, "SMH", 2.0, matrix=False)
        df.loc[df.market == name, ["soxx2x", "smh2x"]] = [s2, m2]
    assert df.loc[df.market == "US", "winner"].iloc[0] == "SMH"
    assert df.loc[df.market == "TECH", "winner"].iloc[0] == "SMH"

    lines = [
        "# Core: SOXX vs SMH",
        "",
        "Generated by `uv run python scripts/core.py`. Same rules, same window",
        "(2015-2026), 1x unless stated; the only change is the semis ETF in the core slot.",
        "",
        "| market | SOXX $10k | SMH $10k | SOXX maxDD | SMH maxDD | SOXX Sharpe | SMH Sharpe | winner |",
        "|---|---:|---:|---:|---:|---:|---:|---|",
    ]
    for _, r in df.iterrows():
        lines.append(
            f"| {r.label} | ${r.soxx:,.0f} | ${r.smh:,.0f} | {r.soxx_dd:.1%} | "
            f"{r.smh_dd:.1%} | {r.soxx_sh:.2f} | {r.smh_sh:.2f} | **{r.winner}** |"
        )
    lines += [
        "",
        "## At 2x, pre-trend config (40% sector cap)",
        "",
        "| market | SOXX | SMH | SMH / SOXX |",
        "|---|---:|---:|---:|",
    ]
    for _, r in df.dropna(subset=["smh2x"]).iterrows():
        lines.append(
            f"| {r.label} | ${r.soxx2x:,.0f} | **${r.smh2x:,.0f}** | {r.smh2x / r.soxx2x:.2f}x |"
        )
    lines += [
        "",
        "## Reading",
        "",
        f"- SMH wins in {int((df.winner == 'SMH').sum())}/{len(df)} markets, including both",
        "  markets the bot actually runs by default (S&P and Nasdaq tech).",
        "- In Europe SOXX usually wins: the local sleeve and the EUR conversion change the",
        "  path, and SMH's extra NVDA concentration cuts both ways. `--core SOXX` keeps the",
        "  old behaviour per run.",
        "- SMH is not a new signal or a new asset class. It is the same semis bet with a",
        "  more concentrated index. The 2015-2026 result is still one industry's decade.",
        "- The switch was made on this path. Both funds existed in 2015, so there is no",
        "  backfill, but the choice itself is in-sample.",
        "",
    ]
    out = Path(__file__).resolve().parent.parent / "results" / "core.md"
    out.write_text("\n".join(lines))
    print(df.round(4).to_string(index=False))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
